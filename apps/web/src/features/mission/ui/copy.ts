export type MissionCopyKey = keyof typeof MISSION_COPY
export type MissionCopyParameters = Readonly<Record<string, string | number>>

function interpolate(value: string, parameters: MissionCopyParameters): string {
  return value.replace(/\{([^}]+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(parameters, key) ? String(parameters[key]) : match
  )
}

export function missionFallback(
  key: MissionCopyKey,
  locale: string,
  parameters: MissionCopyParameters = {}
): string {
  const copy = MISSION_COPY[key]
  return interpolate(locale === 'CH' ? copy.zh : copy.en, parameters)
}

